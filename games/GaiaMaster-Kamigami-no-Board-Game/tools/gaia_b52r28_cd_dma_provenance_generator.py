#!/usr/bin/env python3
from __future__ import annotations
import argparse,csv
from pathlib import Path

RAM=0x200000

def hx(s): return int(str(s).strip(),16)
def count16(v): return v if v else 0x10000

def load_events(p):
    out=[]
    with p.open('r',encoding='utf-8-sig',newline='') as f:
        for r in csv.DictReader(f,delimiter='\t'):
            r['_value']=hx(r['value']); out.append(r)
    return out

def target_ranges(ev):
    starts=[i for i,e in enumerate(ev) if e['hw']=='DMA2_CHCR' and ((e['_value']>>24)&1)]
    if not starts: raise RuntimeError('No DMA2_CHCR start event in B52R24 trace')
    i=starts[-1]; madr=bcr=None
    for e in ev[:i+1]:
        if e['hw']=='DMA2_MADR': madr=e['_value']
        elif e['hw']=='DMA2_BCR': bcr=e['_value']
    if madr is None or bcr is None: raise RuntimeError('Missing DMA2 MADR/BCR before start')
    ch=ev[i]['_value']; sync=(ch>>9)&3; step=(ch>>1)&1
    if sync==0: words=count16(bcr&0xffff)
    elif sync==1: words=count16(bcr&0xffff)*count16((bcr>>16)&0xffff)
    else: raise RuntimeError('B52R28 requires a linear B52R24 target (DMA2 SyncMode 0/1); SyncMode 2 is command-list RAM')
    words=min(words,RAM//4); n=words*4; m=madr&0x1fffff
    if step==0: start=m
    else: start=(m-(n-4))%RAM
    if start+n<=RAM: ranges=[(start,n)]
    else: ranges=[(start,RAM-start),(0,n-(RAM-start))]
    return ranges,dict(madr=madr,bcr=bcr,chcr=ch,sync=sync,step=step,words=words)

