def selftest():
    rows=[
      {'hw':'DMA2_MADR','_value':0x1000},
      {'hw':'DMA2_BCR','_value':0x00010004},
      {'hw':'DMA2_CHCR','_value':0x01000201},
    ]
    r,m=target_ranges(rows)
    assert r==[(0x1000,16)] and m['sync']==1 and 'DMA3_CHCR' in lua_for(r,m) and 'Setloc' in lua_for(r,m)
    print('B52R28 CD DMA PROVENANCE GENERATOR SELFTEST PASS')

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('trace',nargs='?',type=Path); ap.add_argument('-o','--output',type=Path); ap.add_argument('--selftest',action='store_true'); a=ap.parse_args()
    if a.selftest:selftest();return 0
    if not a.trace:ap.error('B52R24 TRACE.tsv required')
    ranges,meta=target_ranges(load_events(a.trace))
    out=a.output or a.trace.with_name('GaiaMaster_B52R28_PCSX_CD_DMA_PROVENANCE.lua')
    out.write_text(lua_for(ranges,meta),encoding='utf-8')
    print(f'Generated {out}; target_ranges={ranges}')
    return 0
if __name__=='__main__': raise SystemExit(main())
