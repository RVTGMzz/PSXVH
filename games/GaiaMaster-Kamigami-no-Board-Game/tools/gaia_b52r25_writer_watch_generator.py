#!/usr/bin/env python3
from __future__ import annotations
import argparse,csv
from pathlib import Path

RAM=0x200000

def hx(s): return int(str(s).strip(),16)
def count16(v): return v if v else 0x10000

def load_events(p):
    out=[]
    with p.open('r',encoding='utf-8-sig',newline='') as f:
        for r in csv.DictReader(f,delimiter='\t'):
            r['_value']=hx(r['value']); out.append(r)
    return out

def find_tx(ev):
    starts=[i for i,e in enumerate(ev) if e['hw']=='DMA2_CHCR' and ((e['_value']>>24)&1)]
    if not starts: raise RuntimeError('No DMA2_CHCR start event')
    i=starts[-1]; madr=bcr=None
    for e in ev[:i+1]:
        if e['hw']=='DMA2_MADR': madr=e['_value']
        elif e['hw']=='DMA2_BCR': bcr=e['_value']
    if madr is None: raise RuntimeError('No DMA2_MADR before start')
    if bcr is None: bcr=0
    ch=ev[i]['_value']; sync=(ch>>9)&3; direction=ch&1; step=(ch>>1)&1
    return madr,bcr,ch,sync,direction,step

def watched_ranges(madr,bcr,sync,step):
    if sync==0: words=count16(bcr&0xffff)
    elif sync==1: words=count16(bcr&0xffff)*count16((bcr>>16)&0xffff)
    else: raise RuntimeError('SyncMode 2 is GPU command-list memory, not a linear DMA payload. Capture a SyncMode 0/1 transaction or use GPU-origin tracing.')
    words=min(words,RAM//4); n=words*4; m=madr&0x1fffff
    if step==0: start=m; end=m+n
    else: start=(m-(n-4))%RAM; end=start+n
    if end<=RAM: return [(start,n)],words
    first=RAM-start; return [(start,first),(0,n-first)],words

