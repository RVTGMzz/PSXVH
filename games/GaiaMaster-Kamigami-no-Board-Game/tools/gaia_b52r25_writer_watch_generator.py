def selftest():
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        p=Path(d)/'t.tsv'
        p.write_text('seq\tpc\tra\thw\treg\tvalue\tfunc_start\tscore\n1\t1\t2\tDMA2_MADR\tt0\t00001000\t0\t1\n2\t1\t2\tDMA2_BCR\tt1\t00010004\t0\t1\n3\t1\t2\tDMA2_CHCR\tt2\t01000201\t0\t1\n',encoding='utf-8')
        tx=find_tx(load_events(p)); ranges,words=watched_ranges(tx[0],tx[1],tx[3],tx[5]); lua=make_lua(ranges,words,*tx)
        assert ranges==[(0x1000,16)] and words==4 and 'PCSX.addBreakpoint' in lua and "'Write'" in lua and 'gaia_save25' in lua and '_WRITER_RAM.bin' in lua
    print('B52R25 WRITER WATCH GENERATOR SELFTEST PASS')

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('trace',nargs='?',type=Path); ap.add_argument('-o','--output',type=Path); ap.add_argument('--selftest',action='store_true'); a=ap.parse_args()
    if a.selftest:selftest();return 0
    if not a.trace:ap.error('B52R24 TRACE.tsv required')
    tx=find_tx(load_events(a.trace)); ranges,words=watched_ranges(tx[0],tx[1],tx[3],tx[5]); lua=make_lua(ranges,words,*tx)
    out=a.output or a.trace.with_name('GaiaMaster_B52R25_PCSX_SOURCE_WRITER_WATCH.lua'); out.write_text(lua,encoding='utf-8')
    print(f'Generated {out}; ranges={ranges}; words={words}')
    return 0
if __name__=='__main__': raise SystemExit(main())
